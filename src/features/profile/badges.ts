/**
 * The achievement catalogue.
 *
 * Rules this list is built to:
 *
 * 1. Every badge has a PRECISE, stated criterion evaluated against the user's
 *    real log. Nothing is awarded for opening the app, and nothing is awarded
 *    on the first session — an achievement nobody can fail is decoration, not
 *    an achievement.
 * 2. Every criterion is countable, so a locked badge can show how close it is
 *    rather than just taunting.
 * 3. Rarity is a claim about difficulty, not a colour. Legendary tiers are
 *    genuinely years of training away for most lifters.
 */

export type Rarity = 'common' | 'uncommon' | 'rare' | 'epic' | 'legendary';

export type BadgeCategory = 'consistency' | 'volume' | 'strength' | 'variety' | 'milestone';

export type BadgeUnit = 'count' | 'kg' | 'hours' | 'ratio';

export type BadgeDef = {
  id: string;
  name: string;
  category: BadgeCategory;
  rarity: Rarity;
  icon: LucideIcon;
  /** Shown while locked. Must state the exact bar. */
  criterion: string;
  /** Shown when earned. */
  blurb: string;
  unit: BadgeUnit;
  /** The bar. A function when it depends on the catalogue rather than a constant. */
  target: number | ((s: ProfileStats) => number);
  /** Current standing against the bar. */
  measure: (s: ProfileStats) => number;
};

