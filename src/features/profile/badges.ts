export type EvaluatedBadge = {
  def: BadgeDef;
  value: number;
  target: number;
  earned: boolean;
  /** 0–1. */
  progress: number;
  /** False for one-shot criteria where a bar would just read 0% or 100%. */
  countable: boolean;
};

export function evaluateBadges(stats: ProfileStats): EvaluatedBadge[] {
  const out: EvaluatedBadge[] = [];
  for (const d of BADGES) {
    const target = typeof d.target === 'function' ? d.target(stats) : d.target;
    const value = d.measure(stats);
    const safeTarget = target > 0 ? target : 1;
    out.push({
      def: d,
      value,
      target,
      earned: value >= target && target > 0,
      progress: Math.max(0, Math.min(1, value / safeTarget)),
      countable: target > 1 || d.unit === 'ratio',
    });
  }
  // Earned first, rarest at the top. Then the locked ones ordered by how close
  // they are, so the next thing to chase is always at the front.
  out.sort((a, b) => {
    if (a.earned !== b.earned) return a.earned ? -1 : 1;
    if (a.earned) {
      const r = RARITY_ORDER[b.def.rarity] - RARITY_ORDER[a.def.rarity];
      if (r !== 0) return r;
      return a.def.name.localeCompare(b.def.name);
    }
    if (b.progress !== a.progress) return b.progress - a.progress;
    return RARITY_ORDER[a.def.rarity] - RARITY_ORDER[b.def.rarity];
  });
  return out;
}

/** "34 / 100", "182 / 250 kg", "1.24 / 1.50×". */
export function progressLabel(b: EvaluatedBadge): string {
  const { unit } = b.def;
  if (unit === 'ratio') return `${b.value.toFixed(2)} / ${b.target.toFixed(2)}×`;
  if (unit === 'hours') return `${trim(b.value)} / ${trim(b.target)} h`;
  const value = Math.floor(b.value).toLocaleString('en-US');
  const target = Math.round(b.target).toLocaleString('en-US');
  return unit === 'kg' ? `${value} / ${target} kg` : `${value} / ${target}`;
}

function trim(n: number): string {
  return Number.isInteger(n) ? `${n}` : n.toFixed(1);
}
