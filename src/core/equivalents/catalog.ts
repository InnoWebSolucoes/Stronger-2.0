/** Mass above which an entry is treated as legend-tier, in kg (research PART 3, `nextMilestone`). */
export const MILESTONE_THRESHOLD_KG = 2e7;

/**
 * Entries the finish-screen picker may choose from: everything that is not legend-tier.
 * Sorted ascending by mass, same as the full catalogue.
 */
export const PICKABLE_EQUIVALENTS: readonly MassEquivalent[] = MASS_EQUIVALENTS.filter(
  (e) => !isMilestone(e),
);

/**
 * Legend-tier entries, ascending by mass. These power the lifetime progress line
 * ("3.1% of the Titanic"), never a per-session ratio.
 */
export const MILESTONE_EQUIVALENTS: readonly MassEquivalent[] = MASS_EQUIVALENTS.filter(isMilestone);

/** True when an entry is legend-tier: flagged `milestoneOnly`, or at/above 20,000 tonnes. */
export function isMilestone(entry: MassEquivalent): boolean {
  return entry.milestoneOnly === true || entry.massKg >= MILESTONE_THRESHOLD_KG;
}

const BY_ID: ReadonlyMap<string, MassEquivalent> = new Map(
  MASS_EQUIVALENTS.map((e) => [e.id, e]),
);

/**
 * Look up a catalogue entry by its stable slug.
 * Returns `undefined` for an id that is no longer in the catalogue — an old workout
 * can reference a retired entry, and the caller must render that gracefully.
 */
export function getEquivalent(id: string): MassEquivalent | undefined {
  return BY_ID.get(id);
}

/**
 * How many of `entry` weigh `totalKg`. Both inputs are kilograms.
 * Returns 0 for a non-positive or non-finite total, so an empty session never
 * produces a comparison at all.
 */
export function countOf(totalKg: number, entry: MassEquivalent): number {
  if (!Number.isFinite(totalKg) || totalKg <= 0) return 0;
  return totalKg / entry.massKg;
}
