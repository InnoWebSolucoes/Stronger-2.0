/**
 * Volume equivalents catalogue — real-world masses used by the Finish screen.
 *
 * Source: docs/research/stronger-2-0-volume-equivalents-system-finish-scre.md,
 * "PART 2 - The catalogue". Every mass is transcribed exactly from that brief,
 * which carries a citation per entry; none are rounded for tidiness and none
 * were invented here.
 *
 * Units: every `massKg` is KILOGRAMS, the canonical storage unit of the app.
 * Comparison counts are always computed from kg; display unit conversion happens
 * in the render layer and never touches these numbers.
 *
 * Pure TypeScript: no react / react-native / expo imports, runs under plain node.
 */

/** Broad family of a comparison object. Used to keep the two or three shown picks different. */
export type EquivCategory =
  | 'everyday'
  | 'gym'
  | 'animal'
  | 'vehicle'
  | 'aircraft'
  | 'marine'
  | 'space'
  | 'structure'
  | 'industrial'
  | 'legend';

/**
 * How firm the mass is.
 * - `verified`: a single published figure from the cited primary source (NASA, NPS, a spec sheet).
 * - `representative`: a typical value for something that genuinely varies (a fire engine, a sofa).
 * - `estimate`: a live scientific estimate with a published range (T. rex, Argentinosaurus).
 *
 * The UI should hedge copy ("about 19 tonnes") for anything that is not `verified`.
 */
export type Confidence = 'verified' | 'representative' | 'estimate';

/** One comparable real-world object. `massKg` is kilograms, always. */
export interface MassEquivalent {
  /** Stable slug. Persisted on the workout record, so it must never be regenerated or reordered. */
  readonly id: string;
  /** Bare noun, e.g. "African elephant". */
  readonly name: string;
  /** Article form for the count-of-one case, e.g. "an African elephant". */
  readonly singular: string;
  /** Plural form, e.g. "African elephants". */
  readonly plural: string;
  /** Mass in KILOGRAMS. */
  readonly massKg: number;
  readonly category: EquivCategory;
  /** Fallback glyph. The icon sheet is preferred wherever it has a matching key. */
  readonly emoji: string;
  /** Icon hint — a lucide-style key for the house icon sheet. */
  readonly icon: string;
  /** 0..1 — how likely the user has physically stood next to one. */
  readonly relatability: number;
  /** 0..1 — how good it sounds said out loud. */
  readonly spectacle: number;
  /** Optional one-line fact, <= 90 chars, shown at most once per screen. */
  readonly fun?: string;
  /** Where the mass came from. */
  readonly source: string;
  readonly sourceUrl: string;
  readonly confidence: Confidence;
  /**
   * Legend-tier: too heavy to ever yield a sane per-session count, so it is excluded
   * from the finish-screen picker and drives the lifetime milestone bar instead.
   */
  readonly milestoneOnly?: boolean;
}

